export function translate(locale, key, params = {}) {
  const value = messages[locale]?.[key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return typeof value === "string"
    ? value.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? `{${k}}`)
    : value;
}
export function itemName(data, code, locale = DEFAULT_LOCALE) {
  if (code >= 1 && code <= 9)
    return translate(locale, "mineralNames")[code - 1];
  if (code >= 10 && code <= 12)
    return translate(locale, "specialNames")[code - 10];
  return (
    data.items.find((i) => i.code === code)?.name[locale] ??
    data.items.find((i) => i.code === code)?.name[DEFAULT_LOCALE] ??
    String(code)
  );
}
